export class DeviceInfoDto {
  /** Stable per-install UUID generated by the app and kept in DataStore. */
  @IsString() @Length(8, 128)
  deviceId!: string;

  @IsOptional() @IsString() @MaxLength(128)
  fingerprint?: string;

  @IsOptional() @IsString() @MaxLength(64)
  manufacturer?: string;

  @IsOptional() @IsString() @MaxLength(64)
  model?: string;

  @IsOptional() @IsString() @MaxLength(32)
  osVersion?: string;

  @IsOptional() @Type(() => Number) @IsInt() @Min(1) @Max(100)
  sdkInt?: number;

  @IsOptional() @IsString() @MaxLength(32)
  appVersion?: string;

  @IsOptional() @Type(() => Number) @IsInt()
  appBuild?: number;

  /** Self-reported health flags — the dispatcher sees these before departure. */
  @IsOptional() @IsBoolean()
  batteryOptimisationIgnored?: boolean;

  @IsOptional() @IsBoolean()
  hasBackgroundLocation?: boolean;

  @IsOptional() @IsBoolean()
  hasExactAlarm?: boolean;
}

export class ClaimSessionDto {
  @IsString() @Length(4, 32)
  code!: string;

  /**
   * @IsDefined + @ValidateNested are load-bearing, not decoration.
   *
   * The global ValidationPipe runs with `whitelist: true`, which strips every
   * property that carries no *validation* decorator. @Type is a
   * class-transformer directive, so on its own it does not count — the whole
   * `device` object would be silently removed and the service would throw on
   * `dto.device.deviceId`. Covered by the e2e test.
   */
  @IsDefined()
  @ValidateNested()
  @Type(() => DeviceInfoDto)
  device!: DeviceInfoDto;
}

export class DriverRefreshDto {
  @IsString() @Length(16, 256)
  refreshToken!: string;

  @IsString() @Length(8, 128)
  deviceId!: string;
}

export class DriverEventDto {
  @IsIn([
    'STARTED', 'PAUSED', 'RESUMED', 'GPS_LOST', 'GPS_RECOVERED',
    'NETWORK_LOST', 'NETWORK_RECOVERED', 'BUFFER_OVERFLOW',
    'PERMISSION_REVOKED', 'BATTERY_LOW', 'SERVICE_KILLED',
    'SERVICE_RESTORED', 'NOTE',
  ])
  type!: string;

  @IsOptional() @IsISO8601()
  occurredAt?: string;

  @IsOptional() @IsString() @MaxLength(500)
  message?: string;

  @IsOptional()
  payload?: Record<string, unknown>;
}
