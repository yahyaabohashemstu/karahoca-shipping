import { Type } from 'class-transformer';
import {
  IsBoolean,
  IsDefined,
  IsIn,
  IsInt,
  IsISO8601,
  IsOptional,
  IsString,
  IsUUID,
  Length,
  Max,
  MaxLength,
  Min,
  ValidateNested,
} from 'class-validator';

export class CreateSessionDto {
  @IsUUID()
  orderId!: string;

  @IsUUID()
  shippingCompanyId!: string;

  @IsOptional() @IsUUID()
  driverId?: string;

  @IsOptional() @IsUUID()
  vehicleId?: string;

  /** Used when the carrier swaps in a driver who is not in our master data. */
  @IsOptional() @IsString() @MaxLength(120)
  driverName?: string;

  @IsOptional() @IsString() @MaxLength(40)
  driverPhone?: string;

  @IsOptional() @IsString() @MaxLength(24)
  vehiclePlate?: string;

  @IsOptional() @IsInt() @Min(2) @Max(600)
  pingIntervalSec?: number;

  @IsOptional() @IsInt() @Min(5) @Max(1800)
  idleIntervalSec?: number;

  @IsOptional() @IsInt() @Min(0) @Max(5000)
  minDistanceM?: number;

  @IsOptional() @IsInt() @Min(1) @Max(240)
  maxLifetimeHours?: number;

  /** How long the claim code stays valid before the driver must ask for a new one. */
  @IsOptional() @IsInt() @Min(5) @Max(10080)
  claimTtlMinutes?: number;

  @IsOptional() @IsString() @MaxLength(2000)
  notes?: string;
}

